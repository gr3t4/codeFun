drop policy if exists "profile own read" on public.profiles;
create policy "profile own read" on public.profiles for select to authenticated
using (id=auth.uid());

drop policy if exists "profile own update" on public.profiles;
create policy "profile own update" on public.profiles for update to authenticated
using (id=auth.uid()) with check (id=auth.uid());

drop policy if exists "teachers see group students" on public.profiles;
create policy "teachers see group students" on public.profiles for select to authenticated
using (
  exists(
    select 1
    from public.group_members gm
    join public.school_groups sg on sg.id=gm.group_id
    where gm.student_id=profiles.id and sg.teacher_id=auth.uid()
  )
);

drop policy if exists "teacher groups read" on public.school_groups;
create policy "teacher groups read" on public.school_groups for select to authenticated
using (teacher_id=auth.uid() or public.is_member_of_group(id));

drop policy if exists "teacher groups insert" on public.school_groups;
create policy "teacher groups insert" on public.school_groups for insert to authenticated
with check (
  teacher_id=auth.uid() and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('teacher','admin'))
);

drop policy if exists "teacher groups update" on public.school_groups;
create policy "teacher groups update" on public.school_groups for update to authenticated
using (teacher_id=auth.uid()) with check (teacher_id=auth.uid());

drop policy if exists "members relevant read" on public.group_members;
create policy "members relevant read" on public.group_members for select to authenticated
using (
  student_id=auth.uid() or public.is_teacher_of_group(group_id)
);

drop policy if exists "student own attempts" on public.exercise_attempts;
create policy "student own attempts" on public.exercise_attempts for select to authenticated
using (student_id=auth.uid());

drop policy if exists "teacher group attempts" on public.exercise_attempts;
create policy "teacher group attempts" on public.exercise_attempts for select to authenticated
using (
  exists(
    select 1 from public.group_members gm
    join public.school_groups sg on sg.id=gm.group_id
    where gm.student_id=exercise_attempts.student_id and sg.teacher_id=auth.uid()
  )
);

drop policy if exists "student own progress" on public.student_progress;
create policy "student own progress" on public.student_progress for select to authenticated
using (student_id=auth.uid());

drop policy if exists "teacher group progress" on public.student_progress;
create policy "teacher group progress" on public.student_progress for select to authenticated
using (
  exists(
    select 1 from public.group_members gm
    join public.school_groups sg on sg.id=gm.group_id
    where gm.student_id=student_progress.student_id and sg.teacher_id=auth.uid()
  )
);

