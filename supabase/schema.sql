create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  control_number text,
  username text,
  role text not null default 'student' check (role in ('student','teacher','admin')),
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists username text;

create unique index if not exists profiles_username_lower_idx
  on public.profiles (lower(username)) where username is not null;

-- Gamificación: racha de días consecutivos practicando.
alter table public.profiles add column if not exists streak_current integer not null default 0;
alter table public.profiles add column if not exists streak_best integer not null default 0;
alter table public.profiles add column if not exists streak_last_date date;

create table if not exists public.school_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  code text not null unique,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  school_year text,
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id uuid not null references public.school_groups(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key(group_id, student_id)
);

create table if not exists public.exercise_attempts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  exercise_id text not null,
  subject_id text not null,
  topic text not null,
  answer text,
  correct boolean not null,
  xp integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.student_progress (
  student_id uuid not null references public.profiles(id) on delete cascade,
  subject_id text not null,
  exercises_done integer not null default 0,
  correct_answers integer not null default 0,
  xp integer not null default 0,
  last_activity timestamptz,
  updated_at timestamptz not null default now(),
  primary key(student_id, subject_id)
);

-- Perfil automático al registrarse.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles(id, full_name, control_number, username, role)
  values(
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name',''),
    nullif(new.raw_user_meta_data ->> 'control_number',''),
    nullif(new.raw_user_meta_data ->> 'username',''),
    'student'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Unirse a un grupo usando su código.
create or replace function public.join_group_by_code(p_code text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare v_group uuid;
begin
  select id into v_group
  from public.school_groups
  where upper(code)=upper(trim(p_code));

  if v_group is null then
    raise exception 'Código de grupo no válido';
  end if;

  insert into public.group_members(group_id,student_id)
  values(v_group,auth.uid())
  on conflict do nothing;

  return v_group;
end;
$$;

-- Registrar intento y actualizar resumen del estudiante.
create or replace function public.record_attempt(
  p_exercise_id text,
  p_subject_id text,
  p_topic text,
  p_answer text,
  p_correct boolean,
  p_xp integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.exercise_attempts(student_id,exercise_id,subject_id,topic,answer,correct,xp)
  values(auth.uid(),p_exercise_id,p_subject_id,p_topic,p_answer,p_correct,p_xp);

  insert into public.student_progress(student_id,subject_id,exercises_done,correct_answers,xp,last_activity)
  values(auth.uid(),p_subject_id,1,case when p_correct then 1 else 0 end,p_xp,now())
  on conflict(student_id,subject_id) do update
  set exercises_done=student_progress.exercises_done+1,
      correct_answers=student_progress.correct_answers+case when excluded.correct_answers=1 then 1 else 0 end,
      xp=student_progress.xp+excluded.xp,
      last_activity=now(),
      updated_at=now();

  update public.profiles
  set streak_current = case
        when streak_last_date = current_date then streak_current
        when streak_last_date = current_date - 1 then streak_current + 1
        else 1
      end,
      streak_best = greatest(streak_best, case
        when streak_last_date = current_date then streak_current
        when streak_last_date = current_date - 1 then streak_current + 1
        else 1
      end),
      streak_last_date = current_date
  where id = auth.uid();
end;
$$;

-- Helper functions (security definer = bypass RLS internally) to avoid
-- infinite recursion between the school_groups and group_members policies,
-- since each one otherwise needs to read the other RLS-protected table.
create or replace function public.is_teacher_of_group(p_group_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists(
    select 1 from public.school_groups sg
    where sg.id = p_group_id and sg.teacher_id = auth.uid()
  );
$$;

create or replace function public.is_member_of_group(p_group_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists(
    select 1 from public.group_members gm
    where gm.group_id = p_group_id and gm.student_id = auth.uid()
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Solo un admin puede cambiar el rol de una cuenta (evita que un alumno se
-- autoasigne role='teacher'/'admin' vía un update directo a su propio perfil).
create or replace function public.prevent_self_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Solo se restringe cuando la escritura llega vía PostgREST como un
  -- usuario autenticado normal. Conexiones directas (SQL Editor, CLI,
  -- service_role) no pasan por aquí, para poder crear el primer admin.
  if new.role is distinct from old.role and auth.role()='authenticated' and not public.is_admin() then
    raise exception 'Solo un administrador puede cambiar el rol de una cuenta.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_prevent_self_role_change on public.profiles;
create trigger trg_prevent_self_role_change
before update on public.profiles
for each row execute procedure public.prevent_self_role_change();

